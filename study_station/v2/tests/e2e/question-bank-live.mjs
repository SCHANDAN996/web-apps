// A new disposable learner exercises the real bank + count picker + reading-cache controls.
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const B = process.env.BASE_URL || 'http://127.0.0.1:8011';
if (!/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(B)) throw new Error('Use a local scratch server.');
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
const context = await browser.newContext({ viewport: { width: 360, height: 800 } });
const p = await context.newPage(), errors = []; p.on('pageerror', e => errors.push(e.message));
await p.goto(B + '/');
await p.evaluate(() => navigator.serviceWorker.ready); await p.waitForFunction(() => !!navigator.serviceWorker.controller);
assert.equal((await p.request.post(B + '/api/v1/me', { data: { lang: 'hi', level: '10th', target_exams: [] } })).ok(), true);
await p.goto(B + '/practice'); await p.locator('main .list-item').first().click();
await p.locator('#practiceForm').waitFor();
assert.deepEqual(await p.locator('[name=count]').evaluateAll(items => items.map(e => e.value)), ['10', '20', '50']);
const topicPath = new URL(p.url()).pathname;
await p.locator('label.chip:has(input[name=count][value="50"])').click();
assert.equal(await p.locator('[name=count][value="50"]').isChecked(), true);
const fiftyResponse = p.waitForResponse(r => r.url().endsWith('/api/v1/practice') && r.request().method() === 'POST');
await p.locator('#practiceForm button[type=submit]').click();
const fifty = await (await fiftyResponse).json(); assert.equal(fifty.questions.length, 50);
await p.waitForURL(/\/attempt\/\d+/); await p.locator('.option').first().click(); await p.locator('.action-bar .btn-primary').click(); await p.locator('.feedback').waitFor();
await p.evaluate(path => SS.go(path), topicPath);
await p.locator('a[href^="/questions?"]').click(); await p.locator('#questionBankFilters').waitFor();
assert.equal(await p.locator('main .list-item').count(), 30);
await p.locator('#questionBankFilters summary').click();
await p.selectOption('#questionBankFilters [name=difficulty]', 'easy');
await p.locator('#questionBankFilters button[type=submit]').click();
await p.waitForURL(/difficulty=easy/); assert.ok(await p.locator('main .list-item').count() > 0);
assert.ok(await p.locator('main .list-item').count() <= 30);
assert.equal(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
if (process.env.QA_SCREENSHOT_DIR) await p.screenshot({ path: process.env.QA_SCREENSHOT_DIR + '/question-bank-hi-mobile.png' });
const preservedTopic = new URL(p.url()).searchParams.get('topic');
await p.locator('#langBtn').click(); await p.waitForURL(/lang=en/);
assert.equal(await p.getAttribute('html', 'lang'), 'en');
assert.equal(new URL(p.url()).searchParams.get('topic'), preservedTopic);
assert.equal(new URL(p.url()).searchParams.get('difficulty'), 'easy');
await p.locator('#langBtn').click(); await p.waitForURL(/lang=hi/);
assert.equal(await p.getAttribute('html', 'lang'), 'hi');
const href = await p.locator('main .list-item').first().getAttribute('href'), qid = Number(/\/questions\/(\d+)/.exec(href)[1]);
await p.locator('main .list-item').first().click(); await p.locator('[data-question-practice]').waitFor();
const exactResponse = p.waitForResponse(r => r.url().endsWith('/api/v1/questions/' + qid + '/practice'));
await p.locator('[data-question-practice]').click(); const exact = await (await exactResponse).json();
assert.deepEqual(exact.questions.map(q => q.id), [qid]);
await p.waitForURL(/\/attempt\/\d+/); await p.locator('.option').first().click(); await p.locator('.action-bar .btn-primary').click(); await p.locator('.feedback').waitFor();
await p.evaluate(() => SS.go('/books')); await p.locator('main .card-link').first().click(); await p.locator('.chapter-list a.list-item').first().click(); await p.locator('.book-body').waitFor();
await p.evaluate(() => SS.go('/settings')); await p.locator('#contentCacheClear:not([disabled])').waitFor();
await p.evaluate(qid => {
  SSTheme.set('paper'); localStorage.setItem('ss_read_chapters', '["/books/keep/chapter"]');
  SSWhiteboard.merge({ [qid]: { updated: Date.now(), strokes: [{ tool: 'pen', color: 'black', points: [[0.1, 0.1]] }] } });
}, qid);
const before = await (await p.request.get(B + '/api/v1/backup/export')).json();
const localBefore = await p.evaluate(() => ({ reading: localStorage.ss_read_chapters, rough: localStorage.ss_whiteboards_v1, theme: localStorage.ss_theme }));
assert.match(await p.locator('#contentCacheStatus').textContent(), /[1-9]/);
await p.locator('#contentCacheClear').click();
await p.waitForFunction(() => document.querySelector('#contentCacheStatus').textContent.includes('साफ हो गए'));
assert.deepEqual(await (await p.request.get(B + '/api/v1/backup/export')).json(), before);
assert.deepEqual(await p.evaluate(() => ({ reading: localStorage.ss_read_chapters, rough: localStorage.ss_whiteboards_v1, theme: localStorage.ss_theme })), localBefore);
const cacheCounts = await p.evaluate(async () => ({ books: (await (await caches.open('ss2-books-v1')).keys()).length, questions: (await (await caches.open('ss2-questions-v1')).keys()).length }));
assert.deepEqual(cacheCounts, { books: 0, questions: 0 });
assert.equal(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
if (process.env.QA_SCREENSHOT_DIR) await p.screenshot({ path: process.env.QA_SCREENSHOT_DIR + '/content-cache-settings-hi-mobile.png' });
assert.deepEqual(errors, []);
console.log('Real50-question session,30/page bankfilters, exact-question practice, mobilelayout and content-only cacheclear preservingprogress passed.');
await browser.close();
