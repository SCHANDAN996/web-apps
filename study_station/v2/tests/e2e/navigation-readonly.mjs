// Actual local-server navigation without learner creation, API writes or progress changes.
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const B = process.env.BASE_URL || 'http://127.0.0.1:8011';
if (!/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(B)) throw new Error('Use a local QA server.');
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
const p = await browser.newPage({ viewport: { width: 360, height: 800 } }), errors = [], writes = [];
p.on('pageerror', e => errors.push(e.message));
p.on('request', request => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()); });
await p.goto(B + '/settings');
await p.waitForFunction(() => !!window.SS?.go);
await p.evaluate(() => SS.go('/jobs?qualification=all'));
await p.locator('#jobSearch').waitFor();
assert.equal(new URL(p.url()).pathname, '/jobs');
await p.evaluate(() => SS.go('/books'));
await p.locator('main .card-link').first().waitFor();
await p.locator('main .card-link').first().click();
await p.waitForURL(/\/books\/[^/]+$/);
await p.locator('.chapter-list a.list-item').first().click();
await p.locator('.book-body').waitFor();
await p.evaluate(() => SS.go('/settings'));
await p.locator('#onboard').waitFor();
await p.goBack();
await p.locator('.book-body').waitFor();
assert.equal(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
assert.deepEqual(writes, []);
assert.deepEqual(errors, []);
console.log('Actual-server jobs/books/chapter/settings/back navigation passed with no writes or JS errors.');
await browser.close();
